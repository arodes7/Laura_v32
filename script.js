function escapeHtml(value) {
  return String(value ?? '')
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#039;');
}

function labelForTipo(tipo) {
  if (tipo?.includes('regalo')) return 'regalo';
  if (tipo?.includes('pista')) return 'pista';
  if (tipo?.includes('broma')) return 'broma';
  if (tipo?.includes('vale')) return 'vale';
  if (tipo === 'final') return 'final';
  return 'mensaje';
}

function matchesFilter(feature) {
  if (state.filter === 'todos') return true;
  if (state.filter === 'regalos') return feature.tipo.includes('regalo') || feature.tipo === 'vale';
  if (state.filter === 'pistas') return feature.tipo.includes('pista') || Boolean(feature.payload);
  if (state.filter === 'bromas') return feature.tipo.includes('broma') || feature.tipo.includes('falsa');
  if (state.filter === 'mensajes') return feature.tipo === 'mensaje' || feature.tipo.includes('emocional') || feature.tipo === 'final' || feature.tipo === 'apertura';
  return true;
}

function matchesSearch(feature) {
  const q = state.search.trim().toLowerCase();
  if (!q) return true;
  return [feature.feature, feature.obra, feature.tipo, feature.formato, feature.estado, feature.mensaje, feature.pista]
    .filter(Boolean)
    .join(' ')
    .toLowerCase()
    .includes(q);
}

function getVisibleFeatures() {
  return featuresLauraV32.filter((feature) => matchesFilter(feature) && matchesSearch(feature));
}

function renderStats() {
  const regalos = featuresLauraV32.filter((f) => f.tipo.includes('regalo') || f.tipo === 'vale').length;
  const pistas = featuresLauraV32.filter((f) => f.tipo.includes('pista') || f.payload).length;
  const bromas = featuresLauraV32.filter((f) => f.tipo.includes('broma') || f.tipo.includes('falsa')).length;
  statsRoot.innerHTML = `
    <span><strong>${featuresLauraV32.length}</strong> features</span>
    <span><strong>${regalos}</strong> regalos/vales</span>
    <span><strong>${pistas}</strong> pistas</span>
    <span><strong>${bromas}</strong> bromas</span>
  `;
}

function renderMetaRows(feature) {
  const rows = [
    ['obra', feature.obra],
    ['formatoObra', feature.formatoObra],
    ['tipo', feature.tipo],
    ['formato', feature.formato],
    ['localizacion', feature.localizacion],
    ['estado', feature.estado],
    ['pista', feature.pista]
  ];

  return rows.map(([key, value]) => `
    <div class="meta-row">
      <dt>${escapeHtml(key)}</dt>
      <dd>${value === null ? '<span class="muted">null</span>' : escapeHtml(value)}</dd>
    </div>
  `).join('');
}

function renderPayload(feature) {
  if (!feature.payload) return '';
  return `
    <section class="payload-block">
      <div class="payload-title">payload</div>
      <code>${escapeHtml(feature.payload)}</code>
      <button class="copy-btn" data-copy="${escapeHtml(feature.payload)}">copiar payload</button>
    </section>
  `;
}

