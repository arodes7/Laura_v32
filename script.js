let currentIndex = 0;
let indexVisible = false;

const featureCard = document.querySelector("#featureCard");
const featureIndex = document.querySelector("#featureIndex");
const progressText = document.querySelector("#progressText");
const progressBar = document.querySelector("#progressBar");
const previousButton = document.querySelector("#previousFeature");
const nextButton = document.querySelector("#nextFeature");
const toggleAllButton = document.querySelector("#toggleAll");

function displayValue(value) {
  if (value === null || value === undefined) return "null";
  return String(value);
}

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function keyValue(key, value) {
  return `
    <div class="kv">
      <span class="kv__key">${escapeHtml(key)}</span>
      <span class="kv__value">${escapeHtml(displayValue(value))}</span>
    </div>
  `;
}

function renderFeature() {
  const feature = featuresLauraV32[currentIndex];
  const percent = ((currentIndex + 1) / featuresLauraV32.length) * 100;

  progressText.textContent = `Feature ${currentIndex + 1} de ${featuresLauraV32.length}`;
  progressBar.style.width = `${percent}%`;
  previousButton.disabled = currentIndex === 0;
  nextButton.disabled = currentIndex === featuresLauraV32.length - 1;

  const fields = [
    ["obra", feature.obra],
    ["formatoObra", feature.formatoObra],
    ["tipo", feature.tipo],
    ["formato", feature.formato],
    ["localizacion", feature.localizacion],
    ["estado", feature.estado],
    ["pista", feature.pista]
  ];

  const payloadHtml = feature.payload
    ? `<div class="payload"><strong>payload:</strong><br>${escapeHtml(feature.payload)}</div>
       <button class="decode-button" type="button" id="decodePayload">Decodificar payload</button>
       <div class="decoded hidden" id="decodedPayload"></div>`
    : "";

  featureCard.innerHTML = `
    <div class="feature-card__header">
      <div class="feature-number">FEATURE #${String(feature.id).padStart(2, "0")}</div>
      <h2 class="feature-name">${escapeHtml(feature.feature)}</h2>
    </div>
    <div class="feature-card__body">
      <div class="object-grid">
        ${fields.map(([key, value]) => keyValue(key, value)).join("")}
      </div>
      <div class="message">${escapeHtml(feature.mensaje)}</div>
      ${payloadHtml}
    </div>
  `;

  const decodeButton = document.querySelector("#decodePayload");
  if (decodeButton) {
    decodeButton.addEventListener("click", () => {
      const decoded = document.querySelector("#decodedPayload");
      decoded.classList.remove("hidden");
      decoded.textContent = feature.mensajeDecodificado;
    });
  }
}

function renderIndex() {
  featureIndex.innerHTML = `
    <div class="index-grid">
      ${featuresLauraV32.map((feature, index) => `
        <button class="index-item" type="button" data-index="${index}">
          #${String(feature.id).padStart(2, "0")} ${escapeHtml(feature.feature)}
        </button>
      `).join("")}
    </div>
  `;

  featureIndex.querySelectorAll("button").forEach((button) => {
    button.addEventListener("click", () => {
      currentIndex = Number(button.dataset.index);
      renderFeature();
      window.scrollTo({ top: featureCard.offsetTop - 18, behavior: "smooth" });
    });
  });
}

previousButton.addEventListener("click", () => {
  currentIndex = Math.max(0, currentIndex - 1);
  renderFeature();
});

nextButton.addEventListener("click", () => {
  currentIndex = Math.min(featuresLauraV32.length - 1, currentIndex + 1);
  renderFeature();
});

toggleAllButton.addEventListener("click", () => {
  indexVisible = !indexVisible;
  featureIndex.classList.toggle("hidden", !indexVisible);
  toggleAllButton.textContent = indexVisible ? "Ocultar índice" : "Ver índice";
});

renderFeature();
renderIndex();
