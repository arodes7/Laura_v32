function renderCards() {
  const visibleFeatures = getVisibleFeatures();
  cardsRoot.innerHTML = visibleFeatures.map(renderCard).join('');

  if (!visibleFeatures.length) {
    cardsRoot.innerHTML = '<p class="empty">No hay features que coincidan con esa búsqueda</p>';
  }
}

function renderModal(feature) {
  modalBody.innerHTML = `
    <div class="modal-hero">
      <div class="art-wrap modal-art">
        <img src="${escapeHtml(feature.image)}" alt="${escapeHtml(feature.obra)}" onerror="this.style.display='none'; this.closest('.art-wrap').classList.add('is-missing');">
        <div class="missing-note">
          <span>imagen pendiente</span>
          <code>${escapeHtml(feature.image)}</code>
        </div>
      </div>
      <div>
        <div class="card-topline">
          <span class="number">#${String(feature.id).padStart(2, '0')}</span>
          <span class="badge badge-${labelForTipo(feature.tipo)}">${escapeHtml(labelForTipo(feature.tipo))}</span>
        </div>
        <h2>${escapeHtml(feature.feature)}</h2>
        <p class="obra">${escapeHtml(feature.obra)} · ${escapeHtml(feature.formatoObra)}</p>
      </div>
    </div>

    <section class="object-panel">
      <div class="object-title">featureObject</div>
      <dl>${renderMetaRows(feature)}</dl>
    </section>

    <section class="message-panel">
      <div class="object-title">mensaje</div>
      <p>${escapeHtml(feature.mensaje).replaceAll('\n', '<br><br>')}</p>
    </section>

    ${renderPayload(feature)}
  `;
  modal.showModal();
}

function setupEvents() {
  filterButtons.forEach((button) => {
    button.addEventListener('click', () => {
      filterButtons.forEach((btn) => btn.classList.remove('active'));
      button.classList.add('active');
      state.filter = button.dataset.filter;
      renderCards();
    });
  });

  searchInput.addEventListener('input', (event) => {
    state.search = event.target.value;
    renderCards();
  });

  cardsRoot.addEventListener('click', (event) => {
    const card = event.target.closest('.card');
    if (!card) return;
    const feature = featuresLauraV32.find((item) => item.id === Number(card.dataset.id));
    if (feature) renderModal(feature);
  });

  closeModal.addEventListener('click', () => modal.close());
  modal.addEventListener('click', (event) => {
    if (event.target === modal) modal.close();
  });

  document.addEventListener('click', async (event) => {
    const copyButton = event.target.closest('[data-copy]');
    if (!copyButton) return;
    try {
      await navigator.clipboard.writeText(copyButton.dataset.copy);
      copyButton.textContent = 'copiado';
      setTimeout(() => copyButton.textContent = 'copiar payload', 1200);
    } catch (error) {
      copyButton.textContent = 'no se pudo copiar';
    }
  });
}

renderStats();
renderCards();
setupEvents();
